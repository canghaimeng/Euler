"""Native Grok CLI provider. Persistent/resume flags are opt-in configuration.

Grok ignores untrusted project-scoped ``.grok/config.toml`` at execution time
even when an inspect list shows it. Generated workers therefore launch with an
isolated ``GROK_HOME`` whose user ``config.toml`` is the stamped Euler MCP
config. Auth is linked from ``EULER_GROK_AUTH_FILE`` or the caller's original
``GROK_HOME`` / default home; it is never copied into tracked sources and
global stores are not overwritten. Proxy variables, when present, are inherited
from the launch environment — this module does not embed machine-specific
network values.
"""

