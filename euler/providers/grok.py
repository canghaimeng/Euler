GROK_KEY_AUTH_VARS: tuple[str, ...] = (
    "XAI_API_KEY",
    "EULER_GROK_API_KEY",
    "GROK_API_KEY",
)
_COMPAT_OFF = {
    "GROK_CURSOR_MCPS_ENABLED": "false",
    "GROK_CLAUDE_MCPS_ENABLED": "false",
}


def _toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _load_toml(path: Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    try:
        import tomllib
    except ImportError:  # Python 3.10
        import tomli as tomllib  # type: ignore
    return tomllib.loads(text)


def isolated_worker_grok_home(worker_dir: Path) -> Path:
    """Per-worker GROK_HOME. User config is ``<home>/config.toml``."""
    return Path(worker_dir) / ".grok"


def grok_key_auth_present(env: Mapping[str, str]) -> bool:
    return any(str(env.get(key) or "").strip() for key in GROK_KEY_AUTH_VARS)


def render_euler_mcp_toml(python: str, env: Mapping[str, str]) -> str:
    """Render core MCP plus the separate control MCP for an explicit main role.

    This does not launch a coordinator. The caller must use the generated file
    as its isolated GROK_HOME/config.toml when starting its main session.
    """
    env_lines = "\n".join(
        f"{key} = {_toml_str(str(val))}" for key, val in env.items()
    )
    text = (
        "# Auto-generated by euler; do not hand-edit.\n"
        "[mcp_servers.euler]\n"
        f"command = {_toml_str(python)}\n"
        'args = ["-m", "euler.gateway"]\n'
        "enabled = true\n"
        "startup_timeout_sec = 20\n"
        "tool_timeout_sec = 3600\n\n"
        "[mcp_servers.euler.env]\n"
        f"{env_lines}\n"
    )
    if env.get("EULER_ROLE") == "main":
        text += (
            "\n[mcp_servers.euler-control]\n"
            f"command = {_toml_str(python)}\n"
            'args = ["-m", "euler.control.mcp"]\n'
            "enabled = true\n"
            "startup_timeout_sec = 20\n"
            "tool_timeout_sec = 3600\n\n"
            "[mcp_servers.euler-control.env]\n"
            f"{env_lines}\n"
        )
    return text


def validate_effective_grok_config(
    path: Path, *, expected_role: str, expected_python: str | None = None,
    expected_project_dir: Path | None = None, expected_author: str | None = None,
    expected_verify_url: str | None = None,
) -> Optional[str]:
    """Return a failure reason, or None when the user config is Euler-ready."""
    if not path.is_file():
        return f"effective Grok user config is missing: {path}"
    try:
        data = _load_toml(path)
    except Exception as exc:
        return f"effective Grok user config is unreadable: {exc}"
    servers = data.get("mcp_servers")
    if not isinstance(servers, dict) or "euler" not in servers:
        return "effective Grok user config has no [mcp_servers.euler] table"
    section = servers["euler"]
    if not isinstance(section, dict):
        return "[mcp_servers.euler] is not a table"
    if section.get("enabled") is False:
        return "effective Grok Euler MCP is disabled"
    args = section.get("args")
    if args != ["-m", "euler.gateway"]:
        return f"effective Grok MCP args must be ['-m', 'euler.gateway'], got {args!r}"
    command = section.get("command")
    if not isinstance(command, str) or not command.strip():
        return "effective Grok MCP command is missing"
    if expected_python is not None:
        # Venv executables may resolve to the same base binary while importing
        # different Euler installations. Preserve the venv path spelling.
        expected_command = os.path.abspath(os.path.expanduser(expected_python))
        if not Path(command).expanduser().is_absolute() or os.path.abspath(os.path.expanduser(command)) != expected_command:
            return f"effective Grok MCP command {command!r} is not this interpreter {expected_command!r}"
    table = section.get("env")
    if not isinstance(table, dict):
        return "effective Grok MCP env table is missing"
    role = table.get("EULER_ROLE")
    if role != expected_role:
        return f"effective Grok EULER_ROLE must be {expected_role!r}, got {role!r}"
    if expected_project_dir is not None:
        project_dir = table.get("EULER_PROJECT_DIR")
        if not isinstance(project_dir, str) or not project_dir.strip():
            return "effective Grok EULER_PROJECT_DIR is missing"
        if Path(project_dir).expanduser().resolve() != expected_project_dir.resolve():
            return "effective Grok EULER_PROJECT_DIR does not match this worker's project"
    if expected_author is not None and table.get("EULER_AUTHOR") != expected_author:
        return "effective Grok EULER_AUTHOR does not match this worker"
    if expected_verify_url is not None and table.get("EULER_VERIFY_URL") != expected_verify_url:
        return "effective Grok EULER_VERIFY_URL does not match this deployment"
    control = servers.get("euler-control")
    if expected_role == "main":
        if not isinstance(control, dict):
            return "effective Grok main config requires [mcp_servers.euler-control]"
        if control.get("enabled") is False:
            return "effective Grok main euler-control MCP is disabled"
        if control.get("command") != command or control.get("args") != ["-m", "euler.control.mcp"]:
            return "effective Grok euler-control must use the same interpreter with -m euler.control.mcp"
        control_env = control.get("env")
        if not isinstance(control_env, dict) or control_env.get("EULER_ROLE") != "main":
            return "effective Grok euler-control EULER_ROLE must be 'main'"
        for key in ("EULER_PROJECT_DIR", "EULER_AGENTS_ROOT", "EULER_AUTHOR", "EULER_VERIFY_URL"):
            if control_env.get(key) != table.get(key):
                return f"effective Grok euler-control {key} differs from the core MCP binding"
    elif "euler-control" in servers:
        return "effective Grok worker/verifier config must not include main-only euler-control"
    return None


def resolve_grok_auth_source(
    env: Mapping[str, str], *, isolated_home: Path | None = None
) -> Optional[Path]:
    """Locate existing auth without reading or copying secret bytes."""
    configured = str(env.get("EULER_GROK_AUTH_FILE") or "").strip()
    if configured:
        return Path(configured).expanduser().resolve()
    original = str(env.get("GROK_HOME") or "").strip()
    if original:
        home = Path(original).expanduser()
        if isolated_home is None or home.resolve() != isolated_home.resolve():
            candidate = home / "auth.json"
            if candidate.is_file():
                return candidate.resolve()
    host = Path(env.get("HOME") or str(Path.home())).expanduser()
    default = host / ".grok" / "auth.json"
    if isolated_home is not None:
        try:
            if default.resolve() == (isolated_home / "auth.json").resolve():
                return None
        except OSError:
            pass
    if default.is_file():
        return default.resolve()
    return None


def link_grok_auth(
    isolated_home: Path, env: Mapping[str, str]
) -> Optional[Path]:
    """Symlink auth into isolated GROK_HOME. Never copies file bytes."""
    source = resolve_grok_auth_source(env, isolated_home=isolated_home)
    if source is None or not source.is_file():
        return None
    isolated_home.mkdir(parents=True, exist_ok=True)
    dest = isolated_home / "auth.json"
    try:
        if (dest.is_symlink() or dest.is_file()) and dest.resolve() == source.resolve():
            return dest
    except OSError:
        pass
    if dest.is_symlink() or dest.exists():
        dest.unlink()
    dest.symlink_to(source)
    return dest


def apply_isolated_grok_launch_env(
    env: Mapping[str, str], isolated_home: Path
) -> dict[str, str]:
    out = dict(env)
    out["GROK_HOME"] = str(isolated_home)
    out.update(_COMPAT_OFF)
    return out


def prepare_isolated_grok_home(
    worker_dir: Path, env: Mapping[str, str]
) -> Path:
    """Ensure the worker GROK_HOME exists and auth is linked when available."""
    home = isolated_worker_grok_home(worker_dir)
    home.mkdir(parents=True, exist_ok=True)
    link_grok_auth(home, env)
    return home


def native_mcp_doctor_command(binary: str, server_name: str = "euler") -> tuple[str, ...]:
    return (binary, "mcp", "doctor", server_name, "--json")


def run_native_mcp_doctor(
    *,
    binary: str,
    isolated_home: Path,
    cwd: Path,
    env: Mapping[str, str],
    timeout_sec: float = 30.0,
    server_name: str = "euler",
) -> dict[str, Any]:
    """One-shot local MCP doctor. No restart loop. Does not start production services."""
    launch = apply_isolated_grok_launch_env(env, isolated_home)
    completed = subprocess.run(
        native_mcp_doctor_command(binary, server_name),
        cwd=str(cwd),
        env=launch,
        capture_output=True,
        text=True,
        timeout=timeout_sec,
        check=False,
    )
    payload: Any = None
    text = (completed.stdout or "").strip()
    if text:
        try:
            payload = json.loads(text)
        except json.JSONDecodeError:
            payload = {"raw": text[:2000]}
    return {
        "ok": completed.returncode == 0,
        "returncode": completed.returncode,
        "stdout": text,
        "stderr": (completed.stderr or "")[:2000],
        "payload": payload,
        "grok_home": str(isolated_home),
        "cwd": str(cwd),
        "argv": list(native_mcp_doctor_command(binary, server_name)),
    }


class GrokProvider:
    name = ProviderName.GROK

    def binary(self) -> str:
        return resolve_binary("EULER_GROK_BIN", "grok")

    def readiness(self, request: AgentRequest) -> ProviderReadiness:
        binary = self.binary()
        home = isolated_worker_grok_home(request.worker_dir)
        config = home / "config.toml"
        if not binary_ready(binary):
            return ProviderReadiness(
                ok=False,
                provider=self.name,
                reason=f"provider binary is not executable: {binary}",
                binary=binary,
            )
        reason = validate_effective_grok_config(
            config, expected_role="worker", expected_python=sys.executable,
            expected_project_dir=request.project_dir, expected_author=request.worker_name,
            expected_verify_url=request.env_with_base().get("EULER_VERIFY_URL", "http://127.0.0.1:8091/verify"),
        )
        if reason:
            return ProviderReadiness(
                ok=False,
                provider=self.name,
                reason=reason,
                binary=binary,
                config=str(config),
            )
        return ProviderReadiness(
            ok=True, provider=self.name, binary=binary, config=str(config),
        )

    def scrub_environment(
        self, request: AgentRequest, env: Mapping[str, str]
    ) -> Mapping[str, str]:
        isolated = isolated_worker_grok_home(request.worker_dir)
        cleaned = isolate_provider_env(self.name, env, drop_consult=True)
        return apply_isolated_grok_launch_env(cleaned, isolated)

    def build_command(self, request: AgentRequest) -> AgentCommand:
        binary = self.binary()
        model = request.model or "grok-4.6"
        effort = request.effort or "high"
        resume = (
            request.session_id
            or (request.recovery.get("GROK_RESUME_SESSION") or "").strip()
            or (request.metadata.get("GROK_RESUME_SESSION") or "").strip()
        )
        persistent = _truthy(
            request.recovery.get("GROK_PERSISTENT")
            or request.metadata.get("GROK_PERSISTENT")
            or os.environ.get("EULER_GROK_PERSISTENT")
        )
        argv = [
            binary,
            "--cwd",
            str(request.worker_dir),
            "--model",
            model,
            "--reasoning-effort",
            effort,
            "--permission-mode",
            "bypassPermissions",
            "--no-subagents",
            "--output-format",
            "streaming-json",
        ]
        if resume:
            argv.extend(["--resume", resume])
        if persistent or resume:
            argv.append(request.prompt)
        else:
            argv.extend(["--single", request.prompt])
        base = request.env_with_base()
        prepare_isolated_grok_home(request.worker_dir, base)
        env = self.scrub_environment(request, base)
        return AgentCommand(
            provider=self.name,
            argv=tuple(argv),
            env=env,
            label=self.name.value,
            session_id=resume or None,
            output_format="grok-streaming-json",
        )

    def recover_session(self, receipt: Mapping[str, object]) -> AgentCommand | None:
        session = receipt.get("session_id")
        prompt = receipt.get("prompt")
        if not isinstance(session, str) or not session.strip():
            return None
        if not isinstance(prompt, str):
            return None
        worker = receipt.get("worker_dir")
        project = receipt.get("project_dir")
        if not worker or not project:
            return None
        request = AgentRequest(
            project_dir=project,  # type: ignore[arg-type]
            worker_dir=worker,  # type: ignore[arg-type]
            worker_name=str(receipt.get("worker_name") or "worker"),
            project_id=str(receipt.get("project_id") or "project"),
            prompt=prompt,
            model=str(receipt.get("model") or ""),
            effort=str(receipt.get("effort") or ""),
            role_name=str(receipt.get("role_name") or ""),
            prompt_profile=str(receipt.get("prompt_profile") or ""),
            session_id=session.strip(),
            recovery={"GROK_PERSISTENT": "1"},
        )
        return self.build_command(request)


def _truthy(value: object) -> bool:
    return str(value or "").strip().lower() in {"1", "true", "yes", "on"}
