def _native_roster(model: Optional[str]) -> List[Dict[str, str]]:
    """Balanced, portable roster using only the four native providers."""
    codex_model = model or _default_model()
    return [
        {"name": "codex1", "provider": "codex", "model": codex_model,
         "effort": "high", "role": "researcher"},
        {"name": "codex2", "provider": "codex", "model": codex_model,
         "effort": "high", "role": "researcher"},
        {"name": "grok1", "provider": "grok", "model": "grok-4.6",
         "effort": "high", "role": "researcher"},
        {"name": "grok2", "provider": "grok", "model": "grok-4.6",
         "effort": "high", "role": "researcher"},
        {"name": "claude1", "provider": "claude-code", "model": "",
         "effort": "high", "role": "researcher"},
        {"name": "cursor1", "provider": "cursor", "model": "auto",
         "effort": "router-managed", "role": "researcher"},
    ]


def _parse_role_text(text: str) -> Dict[str, str]:
    out: Dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            out[key.strip()] = value.strip()
    return out


def _roster(roles: Optional[str], model: Optional[str], profile: str) -> List[Dict[str, str]]:
    if roles:
        selected_model = model or ""
        out: List[Dict[str, str]] = []
        for name, base in L.parse_roles(roles):
            parsed = _parse_role_text(L.render_role_file(selected_model, name, base))
            out.append({
                "name": name,
                "base_role": base,
                "provider": parsed.get("PROVIDER", "codex"),
                "model": parsed.get("MODEL", selected_model),
                "effort": parsed.get("REASONING_EFFORT", base),
                "role": parsed.get("ROLE", base),
            })
        return out
    if profile == "native":
        return _native_roster(model)
    if profile == "codex":
        selected_model = model or _default_model()
        return [
            {"name": name, "provider": "codex", "model": selected_model,
             "effort": base, "role": base}
            for name, base in L.parse_roles("high:3,xhigh:4")
        ]
    raise ValueError("unknown profile; expected 'native' or 'codex'")


def do_new(project: str, roles: Optional[str] = None,
           model: Optional[str] = None, profile: str = "native") -> Dict:
    """Scaffold a project dir + one worker home per role. Refuses to clobber an
    existing project dir (no silent overwrite of a live fact graph). Returns
    ``{"project_dir", "workers"}``."""
    pdir = L.project_dir(project)
    if pdir.exists():
        raise SystemExit(f"project already exists: {pdir} (pick another name or remove it)")
    roster = _roster(roles, model, profile)

    L.workers_dir(project).mkdir(parents=True, exist_ok=True)
    (pdir / "global_memory").mkdir(exist_ok=True)
    (pdir / "fact_graph").mkdir(exist_ok=True)

    created: List[str] = []
    worker_meta: List[Dict[str, str]] = []
    for item in roster:
        worker = item["name"]
        wl = L.WorkerLayout(L.worker_dir(project, worker))
        wl.local_memory.mkdir(parents=True, exist_ok=True)
        wl.logs.mkdir(exist_ok=True)

        # static contract + skills (symlinks stay in sync with the repo)
        symlink(L.worker_md(), wl.dir / "AGENTS.md")
        (wl.dir / ".agents").mkdir(exist_ok=True)
        symlink(L.worker_skills_dir(), wl.dir / ".agents" / "skills")

        atomic_write(wl.task, _TASK_PLACEHOLDER)
        if roles:
            atomic_write(
                wl.role,
                L.render_role_file(model or "", worker, item["base_role"]),
            )
            write_worker_configs(wl, read_role_file(wl))
        else:
            role_lines = [
                f"PROVIDER={item['provider']}",
                f"MODEL={item['model']}",
                f"REASONING_EFFORT={item['effort']}",
                f"ROLE={item['role']}",
                f"EULER_AUTHOR={worker}",
            ]
            atomic_write(wl.role, "\n".join(role_lines) + "\n")
            write_worker_configs(wl, item)
        atomic_write(wl.status,
                     json.dumps({"worker": worker, "state": "created", "round": 0}, indent=2))
        created.append(worker)
        worker_meta.append(dict(item))

    meta = {
        "name": project,
        "profile": "custom" if roles else profile,
        "model": model,
        "roles": roles,
        "workers": created,
        "worker_configs": worker_meta,
        "coordinator": "codex-sol",
    }
    atomic_write(pdir / "project.json", json.dumps(meta, ensure_ascii=False, indent=2))
    if os.environ.get('EULER_MILESTONES', '1') != '0':
        from euler.workspace.milestones import enable, checkpoint_if_enabled
        # All worker assignments/notes are included. Shared contract/skills
        # symlinks become self-contained relative links after restoration.
        attachments = {}
        if L.worker_md().parent.is_dir():
            attachments['contracts'] = str(L.worker_md().parent)
        if L.worker_skills_dir().is_dir():
            attachments['skills'] = str(L.worker_skills_dir())
        history = (pdir.parent / '.euler-history' / pdir.name).resolve()
        attachments = {k:v for k,v in attachments.items() if Path(v).resolve() not in history.parents}
        enable(pdir, attachments=attachments)
        checkpoint_if_enabled(pdir)
    return {"project_dir": str(pdir), "workers": created,
            "profile": meta["profile"], "worker_configs": worker_meta}


