# The MCP server is the installed euler gateway (role=worker) launched as a
# module — pinned interface (ARCHITECTURE.md §4): `python -m euler.gateway` +
# EULER_ROLE. `command` is the interpreter the worker loop itself runs on
# (sys.executable — the same Python euler was launched with), so the gateway can
# never resolve to a different `python3` on codex's PATH. It is rewritten every
# time the loop starts, so a moved/rebuilt venv is picked up automatically.
_CODEX_CONFIG = """\
# Auto-generated by euler (rewritten each time the worker loop starts); do not hand-edit.
[mcp_servers.euler]
command = {python}
args = ["-m", "euler.gateway"]
# fact_submit blocks on the verify service (a cold-started codex that can reason
# for minutes on a hard proof); codex's default tool-call timeout is 120s, which
# would abort those legitimate long verifications. Match the verify HTTP timeout.
tool_timeout_sec = 3600

[mcp_servers.euler.env]
EULER_PROJECT_DIR = {project_dir}
EULER_AUTHOR = {author}
EULER_ROLE = "worker"
EULER_VERIFY_URL = {verify_url}
{extra_env}"""

_TASK_PLACEHOLDER = (
    "# Task\n\n(unassigned — the main agent writes your assignment here via "
    "`euler assign`; you read this file at the start of every round)\n"
)


def _verify_url() -> str:
    # each fact_submit POSTs here; the verify service spawns a fresh codex to
    # verify. Standard local endpoint by default; override with EULER_VERIFY_URL.
    return os.environ.get("EULER_VERIFY_URL", "http://127.0.0.1:8091/verify")


def _default_model() -> str:
    return codex.model()


def write_codex_config(wl: "L.WorkerLayout",
                       extra_env: Optional[Mapping[str, str]] = None) -> None:
    """Write the worker's ``.codex/config.toml``, pinning the gateway ``command``
    to THIS interpreter (``sys.executable``). Used at scaffold time and rewritten
    at every loop start (see ``loop.main``), so the worker's gateway always runs on
    the same Python as euler — never a bare ``python3`` that PATH could resolve to
    a different install (which would silently point the worker at another codebase
    / an incompatible ``mcp``). ``extra_env`` stamps round context (run/branch/subgoal)."""
    extra_lines = ""
    if extra_env:
        parts = []
        for key, val in extra_env.items():
            parts.append(f"{key} = {_toml_str(str(val))}")
        if parts:
            extra_lines = "\n".join(parts) + "\n"
    atomic_write(wl.codex_config, _CODEX_CONFIG.format(
        python=_toml_str(sys.executable),
        project_dir=_toml_str(str(wl.project_dir)),
        author=_toml_str(wl.name),
        verify_url=_toml_str(_verify_url()),
        extra_env=extra_lines,
    ))


def _gateway_env(wl: "L.WorkerLayout",
                 extra_env: Optional[Mapping[str, str]] = None) -> Dict[str, str]:
    env = {
        "EULER_PROJECT_DIR": str(wl.project_dir),
        "EULER_AUTHOR": wl.name,
        "EULER_ROLE": "worker",
        "EULER_VERIFY_URL": _verify_url(),
    }
    if extra_env:
        env.update({str(k): str(v) for k, v in extra_env.items()})
    return env


def write_grok_config(wl: "L.WorkerLayout",
                      extra_env: Optional[Mapping[str, str]] = None) -> None:
    """Stamp Euler MCP as this worker's isolated Grok *user* config.

    Native Grok ignores untrusted project-scoped ``.grok/config.toml`` during
    execution. Launch sets ``GROK_HOME`` to ``<worker>/.grok``, so this file is
    the effective user config. Auth is linked, never copied.
    """
    env = _gateway_env(wl, extra_env)
    atomic_write(
        wl.dir / ".grok" / "config.toml",
        render_euler_mcp_toml(sys.executable, env),
    )
    prepare_isolated_grok_home(wl.dir, os.environ)


def write_cursor_config(wl: "L.WorkerLayout",
                        extra_env: Optional[Mapping[str, str]] = None) -> None:
    """Write the Cursor helper's local Euler MCP config (alias of write_cursor_mcp)."""
    write_cursor_mcp(wl, extra_env=extra_env)


def write_cursor_mcp(wl: "L.WorkerLayout",
                     extra_env: Optional[Mapping[str, str]] = None) -> None:
    """Write local ``.cursor/mcp.json`` and optionally merge into a global config.

    The local file is always written. When ``EULER_CURSOR_GLOBAL_MCP_FALLBACK``
    is truthy and ``EULER_CURSOR_GLOBAL_MCP_CONFIG`` names a JSON file, the
    Euler stdio server is merged into that file without dropping unrelated
    servers or sibling keys.
    """
    # Cursor resolves project MCP config from its detected project root. Worker
    # homes live inside the outer Euler Git checkout, so without a nested root it
    # walks upward and ignores ``<worker>/.cursor/mcp.json`` in favour of the
    # outer/global config. A tiny metadata-only repo makes the worker home the
    # unambiguous project root; the command adds the shared project separately.
    if not (wl.dir / ".git").exists():
        subprocess.run(
            ["git", "init", "-q", str(wl.dir)],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    euler_server = {
        "type": "stdio",
        "command": sys.executable,
        "args": ["-m", "euler.gateway"],
        "env": _gateway_env(wl, extra_env),
    }
    payload = {"mcpServers": {"euler": euler_server}}
    atomic_write(
        wl.dir / ".cursor" / "mcp.json",
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
    )
    flag = os.environ.get("EULER_CURSOR_GLOBAL_MCP_FALLBACK", "").strip().lower()
    if flag not in {"1", "true", "yes"}:
        return
    raw = os.environ.get("EULER_CURSOR_GLOBAL_MCP_CONFIG", "").strip()
    if not raw:
        return
    path = Path(raw)
    existing: dict = {}
    if path.is_file():
        try:
            loaded = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            loaded = {}
        if isinstance(loaded, dict):
            existing = loaded
    servers = existing.get("mcpServers")
    if not isinstance(servers, dict):
        servers = {}
        existing["mcpServers"] = servers
    servers["euler"] = euler_server
    atomic_write(path, json.dumps(existing, ensure_ascii=False, indent=2) + "\n")


def write_claude_code_config(wl: "L.WorkerLayout",
                             extra_env: Optional[Mapping[str, str]] = None) -> None:
    """Write the Claude Code helper's local Euler MCP config.

    The configured Claude Code binary (default ``claude``; wrapper such as
    ``claf`` allowed by ``EULER_CLAUDE_CODE_BIN``) keeps existing auth and
    settings; this file adds only the project-scoped Euler gateway.
    """
    payload = {
        "mcpServers": {
            "euler": {
                "type": "stdio",
                "command": sys.executable,
                "args": ["-m", "euler.gateway"],
                "env": _gateway_env(wl, extra_env),
            }
        }
    }
    atomic_write(
        wl.dir / ".claude" / "mcp.json",
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
    )


def write_worker_configs(wl: "L.WorkerLayout", role: Mapping[str, str],
                         extra_env: Optional[Mapping[str, str]] = None) -> None:
    """Refresh the common preflight config and the selected provider config."""
    write_codex_config(wl, extra_env=extra_env)
    provider = provider_from_role(role).value
    if provider == "grok":
        write_grok_config(wl, extra_env=extra_env)
    elif provider == "cursor":
        write_cursor_config(wl, extra_env=extra_env)
    elif provider == "claude-code":
        write_claude_code_config(wl, extra_env=extra_env)
    elif provider == "gemini":
        atomic_write(wl.dir / '.gemini/settings.json', json.dumps({'mcpServers': {'euler': {
            'command': sys.executable, 'args': ['-m', 'euler.gateway'],
            'env': _gateway_env(wl, extra_env), 'trust': True}}}, indent=2) + '\n')


