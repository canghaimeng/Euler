# spawn_loop — detached launch of one worker's outer loop                     #
# --------------------------------------------------------------------------- #

def spawn_loop(wdir: Path) -> int:
    """Launch ``python -m euler.execution <wdir>`` detached in its own process
    group (``start_new_session=True``) so ``euler stop --force`` can ``killpg``
    the loop *and* its in-flight codex child. Returns the child pid."""
    launcher = os.environ.get("EULER_WORKER_LOOP_LAUNCHER")
    if launcher:
        # Deployment-owned launchers may give managed workers an independent
        # service lifetime. All normal dispatch/preflight checks happen before
        # this hook; failures must never fall back to an uncontained process.
        if not Path(launcher).is_absolute():
            raise ValueError("EULER_WORKER_LOOP_LAUNCHER must be absolute")
        result = subprocess.run([launcher, str(wdir.resolve())], check=True,
                                capture_output=True, text=True, timeout=30)
        pid = int(result.stdout.strip())
        if pid <= 1:
            raise ValueError("worker service returned invalid PID")
        return pid
    wl = L.WorkerLayout(wdir)
    wl.logs.mkdir(parents=True, exist_ok=True)
    logf = open(wl.logs / "loop.log", "a", encoding="utf-8")
    try:
        proc = subprocess.Popen(
            [sys.executable, "-m", "euler.execution", str(wdir)],
            stdout=logf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
            start_new_session=True,
        )
    finally:
        logf.close()
    return proc.pid
